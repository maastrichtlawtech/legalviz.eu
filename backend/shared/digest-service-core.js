const { chatComplete } = require('./openrouter-chat');
const {
  normalizeText,
  loadCache,
  saveCacheEntry,
  extractJsonObject,
  normalizeCites,
} = require('./ai-digest-utils');

// The two case-law digest features (per-article and whole-law) differ only in
// their prompt, their input builder, and a couple of caps. Everything below —
// the JSON parse, the "no groundable case law" fallback, the model call, and
// the cache validate/write cycle — was duplicated between them line for line.
// It lives here so a fix or a cache-entry field lands in both at once.
//
// What must NOT move here: prompts, schemas, cache filenames, and the version
// constants each feature stamps onto its entries. Those are what the
// invalidation table in CLAUDE.md is keyed on, and they stay per-feature.

const MAX_THEMES = 6;
const SUMMARY_MAX_CHARS = 1200;
const THEME_NAME_MAX_CHARS = 120;
const THEME_DESCRIPTION_MAX_CHARS = 900;

/** The shape both features return when there is nothing groundable to say. */
function emptyDigest() {
  return { summary: '', themes: [], noCaseLaw: true };
}

/**
 * Parse and ground a themed digest response.
 *
 * A well-formed response can still fail to ground anything, e.g. when the
 * matching cases have no parsed operative-part declarations to cite (older
 * judgment HTML formats often don't parse cleanly). That is treated the same
 * as "no case law" rather than throwing, so the outcome gets cached instead of
 * re-invoking the model on every request for something that can never produce
 * a groundable digest.
 */
function parseThemedDigestJson(text, input, { citeLimit } = {}) {
  const parsed = extractJsonObject(text);
  if (parsed.noCaseLaw === true || (input.cases || []).length === 0) {
    return emptyDigest();
  }

  const summary = normalizeText(parsed.summary, SUMMARY_MAX_CHARS);
  const themes = (Array.isArray(parsed.themes) ? parsed.themes : [])
    .map((theme) => {
      if (!theme || typeof theme !== 'object') return null;
      const name = normalizeText(theme.name, THEME_NAME_MAX_CHARS);
      const description = normalizeText(theme.description, THEME_DESCRIPTION_MAX_CHARS);
      const cites = normalizeCites(theme.cites, input, citeLimit ? { limit: citeLimit } : undefined);
      if (!name || !description || cites.length === 0) return null;
      return { name, description, cites };
    })
    .filter(Boolean)
    .slice(0, MAX_THEMES);

  if (!summary || themes.length === 0) {
    return emptyDigest();
  }

  return { summary, themes, noCaseLaw: false };
}

/**
 * Call the model for a themed digest. Zero cases short-circuits without any
 * model call, which is why the result carries `billed` separately from the
 * caller's `cached` flag.
 */
async function generateThemedDigest(input, {
  apiKey,
  model,
  chatComplete: chatCompleteImpl = chatComplete,
  systemPrompt,
  userPrompt,
  citeLimit,
} = {}) {
  if ((input.cases || []).length === 0) {
    return {
      digest: emptyDigest(),
      model,
      usage: null,
      billed: false,
    };
  }

  const response = await chatCompleteImpl({
    model,
    apiKey,
    temperature: 0.1,
    maxTokens: 4000,
    responseFormat: 'json_object',
    reasoning: { max_tokens: 256, exclude: true },
    messages: [
      { role: 'system', content: systemPrompt },
      { role: 'user', content: userPrompt },
    ],
  });

  return {
    digest: parseThemedDigestJson(response.text, input, { citeLimit }),
    model: response.model || model,
    usage: response.usage || null,
    billed: true,
  };
}

function isServableEntry(entry, {
  cacheVersion,
  schemaVersion,
  promptVersion,
  caseLawCacheVersion,
  sourceHash,
  model,
}) {
  return entry?.version === cacheVersion
    && entry?.schemaVersion === schemaVersion
    && entry?.promptVersion === promptVersion
    && entry?.caseLawCacheVersion === caseLawCacheVersion
    && entry?.sourceHash === sourceHash
    // A "no case law" outcome is model-independent: it was never generated by
    // one, so it must not be invalidated when the configured model changes.
    && (entry?.model === model || entry?.digest?.noCaseLaw === true)
    && Boolean(entry?.digest);
}

/**
 * Serve a themed digest from the on-disk cache, or generate and persist one.
 *
 * `generate()` is the feature's own model call (a `generateThemedDigest`
 * wrapper); `versions` are the feature's stamped cache versions. The entry
 * shape written here is what `CLAUDE.md`'s digest-version bumps invalidate, so
 * changing a field here changes both features' cache compatibility at once.
 */
async function ensureThemedDigest({
  input,
  key,
  sourceHash,
  cacheDir,
  cacheFile,
  cacheVersion,
  schemaVersion,
  promptVersion,
  caseLawCacheVersion,
  model,
  generate,
}) {
  const versions = { cacheVersion, schemaVersion, promptVersion, caseLawCacheVersion, sourceHash, model };
  const cache = cacheDir ? loadCache(cacheDir, cacheFile) : {};
  const cached = cache[key];
  if (isServableEntry(cached, versions)) {
    return {
      digest: cached.digest,
      model: cached.model || model,
      generatedAt: cached.generatedAt || null,
      caseLawCacheVersion: cached.caseLawCacheVersion,
      cached: true,
      billed: false,
    };
  }

  const generated = await generate(input);
  // A "no case law" digest is stored without a model so it stays servable
  // across model changes (see isServableEntry).
  const resolvedModel = generated.digest.noCaseLaw ? null : (generated.model || model);
  let entry = null;
  if (cacheDir) {
    entry = {
      version: cacheVersion,
      schemaVersion,
      promptVersion,
      caseLawCacheVersion,
      sourceHash,
      model: resolvedModel,
      generatedAt: new Date().toISOString(),
      digest: generated.digest,
    };
    saveCacheEntry(cacheDir, cacheFile, key, entry);
  }

  return {
    digest: generated.digest,
    model: resolvedModel,
    usage: generated.usage || null,
    generatedAt: entry?.generatedAt || null,
    caseLawCacheVersion,
    cached: false,
    // Whether a real (billed) model call happened — distinct from `cached`:
    // the zero-case short-circuit in generateThemedDigest also returns
    // `cached: false` (there is no cache entry validated) but never calls the
    // model.
    billed: generated.billed === true,
  };
}

module.exports = {
  MAX_THEMES,
  emptyDigest,
  ensureThemedDigest,
  generateThemedDigest,
  parseThemedDigestJson,
};
